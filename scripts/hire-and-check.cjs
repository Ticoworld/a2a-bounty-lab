const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {Wallet,JsonRpcProvider,Contract,Interface}=require('ethers');
const ROOT=process.argv[4]?path.resolve(process.argv[4]):path.resolve(__dirname,'../agents/one-rule-world');
const DIR=path.resolve(__dirname,'../.local/quality');fs.mkdirSync(DIR,{recursive:true});
const TOKEN='0x5fc5360D0400a0Fd4f2af552ADD042D716F1d168';
const RPC='https://rpc.mainnet.chain.robinhood.com';
const ABI=['function transfer(address,uint256) returns(bool)','function balanceOf(address) view returns(uint256)','event Transfer(address indexed from,address indexed to,uint256 value)'];
const save=(file,value)=>fs.writeFileSync(file,JSON.stringify(value,null,2));
const read=file=>JSON.parse(fs.readFileSync(file,'utf8'));
let activeProvider;
async function main(){
 const id=process.argv[2],inputFile=process.argv[3];
 if(!/^[a-z0-9-]+$/.test(id||''))throw Error('Supply a unique test id');
 const resultFile=path.join(DIR,id+'.json');
 if(fs.existsSync(resultFile)&&read(resultFile).response)throw Error('Test already has a response; refusing duplicate payment');
 const q=fs.readFileSync(inputFile,'utf8').trim();
 const config=read(path.join(ROOT,'agent.json'));
 const slug=config.name.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'').slice(0,24);
 const url=new URL(`https://api.a2a.family/a/${slug}/v1/ask`);url.searchParams.set('q',q);
 const pub=read(path.join(ROOT,'wallet-public.json'));
 const key=fs.readFileSync(0,'utf8').trim();
 const provider=new JsonRpcProvider(RPC,4663,{staticNetwork:true});activeProvider=provider;
 const wallet=new Wallet(key,provider);
 if(wallet.address!==pub.address)throw Error('Wrong signer');
 const chain=await provider.send('eth_chainId',[]);if(BigInt(chain)!==4663n)throw Error('Wrong chain');
 const ledgerFile=path.join(DIR,'spend-ledger.json');
 const ledger=fs.existsSync(ledgerFile)?read(ledgerFile):{serviceUnits:'0',gasWei:'0',limitServiceUnits:'100000',limitGasWei:'50000000000000',payments:[]};
 let record=fs.existsSync(resultFile)?read(resultFile):null;
 if(record&&record.url!==url.href)throw Error('Cannot reuse a transaction for changed input');
 if(!record){
  const quoteRes=await fetch(url,{signal:AbortSignal.timeout(20000)});
  const quote=await quoteRes.json();
  if(quoteRes.status!==402)throw Error('Expected HTTP 402');
  const option=quote.accepts?.find(a=>a.scheme==='a2a-tx'&&a.asset?.toLowerCase()===TOKEN.toLowerCase());
  const quotedURL=option?.resource?new URL(option.resource):null;
  const sameResource=quotedURL&&quotedURL.origin===url.origin&&quotedURL.pathname===url.pathname&&quotedURL.searchParams.toString()===url.searchParams.toString();
  if(!option||option.network!=='robinhood'||option.payTo?.toLowerCase()!==wallet.address.toLowerCase()||!sameResource)throw Error('Quote binding failed');
  const amount=BigInt(option.maxAmountRequired);
  if(amount!==10000n)throw Error('Unexpected call price');
  if(BigInt(ledger.serviceUnits)+amount>BigInt(ledger.limitServiceUnits))throw Error('Authorized service-test budget exhausted');
  const token=new Contract(TOKEN,ABI,wallet);
  if(await token.balanceOf(wallet.address)<amount)throw Error('Insufficient USDG');
  const gasPrice=BigInt(await provider.send('eth_gasPrice',[]))*125n/100n;
  const estimate=await token.transfer.estimateGas(wallet.address,amount);
  const gasLimit=estimate*120n/100n+1000n;
  if(BigInt(ledger.gasWei)+gasLimit*gasPrice>BigInt(ledger.limitGasWei))throw Error('Authorized gas budget would be exceeded');
  if(await provider.getBalance(wallet.address)<gasLimit*gasPrice)throw Error('Insufficient gas');
  const promptHash=crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT,'system-prompt.txt'))).digest('hex');
  const tx=await token.transfer(wallet.address,amount,{type:0,gasPrice,gasLimit});
  record={id,at:new Date().toISOString(),selfFundedTest:true,url:url.href,input:q,promptHash,quote:option,tx:tx.hash,response:null};
  save(resultFile,record);
  ledger.serviceUnits=String(BigInt(ledger.serviceUnits)+amount);ledger.payments.push({id,tx:tx.hash,serviceUnits:String(amount),status:'broadcast'});save(ledgerFile,ledger);
  const receipt=await tx.wait(1,60000);
  if(!receipt||receipt.status!==1)throw Error('Transfer not confirmed successfully');
  const iface=new Interface(ABI);
  const matching=receipt.logs.filter(log=>log.address.toLowerCase()===TOKEN.toLowerCase()).some(log=>{try{const e=iface.parseLog(log);return e?.name==='Transfer'&&e.args.from.toLowerCase()===wallet.address.toLowerCase()&&e.args.to.toLowerCase()===wallet.address.toLowerCase()&&e.args.value===amount;}catch{return false;}});
  if(!matching)throw Error('Matching Transfer event missing');
  const gasUsed=receipt.gasUsed*receipt.gasPrice;
  ledger.gasWei=String(BigInt(ledger.gasWei)+gasUsed);ledger.payments.at(-1).status='confirmed';save(ledgerFile,ledger);
  record.transferVerified={status:receipt.status,block:receipt.blockNumber,gasUsed:String(receipt.gasUsed),gasPrice:String(receipt.gasPrice),gasWei:String(gasUsed)};save(resultFile,record);
 } else if(!record.transferVerified)throw Error('Pending transfer needs explicit reconciliation before retry');
 const header=Buffer.from(JSON.stringify({x402Version:1,scheme:'a2a-tx',network:'robinhood',payload:{txHash:record.tx}})).toString('base64');
 const start=Date.now();
 const result=await fetch(url,{headers:{'X-PAYMENT':header},signal:AbortSignal.timeout(120000)});
 const text=await result.text();let body;try{body=JSON.parse(text)}catch{body={raw:text}};
 record.httpStatus=result.status;record.durationMs=Date.now()-start;record.response=body;record.paymentResponse=result.headers.get('x-payment-response');save(resultFile,record);
 console.log(JSON.stringify({id,tx:record.tx,httpStatus:result.status,durationMs:record.durationMs,response:body,spentServiceUnits:ledger.serviceUnits,spentGasWei:ledger.gasWei},null,2));
 if(!result.ok)process.exitCode=1;
}
main().catch(e=>{console.error(e.shortMessage||e.message);process.exitCode=1}).finally(()=>activeProvider?.destroy());
